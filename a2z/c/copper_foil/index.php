<tr>
<td><img src="images/copper.jpg" width="150" height="115"></td>
<td>
  <p>Copper foil comes in different forms - on rolls, little pieces, and even as rolls of adhesive copper tape. </p>
  <p>You can cut it to any size or shape; it folds; and is easy to glue or tape to your project. </p>
  <p>The copper can have sharp edges, so handle it carefully so that you don't get cut. </p></td>
</tr>

<tr>
<td colspan="2"><img src="/a2z/images/line_500.gif" width="502" height="12"></td>
</tr>

<tr>
<td><img src="images/alligators.jpg" width="150" height="116"></td>
<td>
  <p>Pieces of copper work well with alligator clip sensors. Copper is a good conductor of electricity -- and it can extend the little tip of the alligator clip. </p>
  <p>You can attach copper foil to places you wouldn't have room to attach a clip. </p></td>
</tr>

<tr>
<td colspan="2"><img src="/a2z/images/line_500.gif" width="502" height="12"></td>
</tr>

<tr>
<td><img src="images/alligators_detail.jpg" width="150" height="116"></td>
<td>
  <p>If you use alligator clips, just clip them on to the copper foil. </p>
  <p>(If you don't have alligator clips, you can just attach a piece of wire to the foil.) </p></td>
</tr>

<tr>
<td colspan="2"><img src="/a2z/images/line_500.gif" width="502" height="12"></td>
</tr>

<tr>
<td><img src="images/marblemachine.jpg" width="150" height="113"></td>
<td>
  <p>Copper foil is great for sensing a metal ball. (It's easier to trigger than a switch or touch sensor.) </p>
  <p>In the photo, two pieces of copper are placed about 1/4-inch apart. Then, the alligator clip sensor is attached to the copper. When the metal marble rolls along the copper, it completes the circuit (and trips the sensor). </p></td>
</tr>

<tr>
<td colspan="2"><img src="/a2z/images/line_500.gif" width="502" height="12"></td>
</tr>

<tr>
<td><img src="images/littleguy.jpg" width="150" height="124"></td>
<td>
  <p>Here I used a piece of copper to make a little plastic figure into a sensor. </p>
  <p>I folded the copper down the back of his legs and under his feet, taped it on, then used a alligator clip to grab the end of the copper. </p></td>
</tr>

<tr>
<td colspan="2"><img src="/a2z/images/line_500.gif" width="502" height="12"></td>
</tr>

<tr>
<td><img src="images/guy_on_map.jpg" width="150" height="113"></td>
<td>I can move the sensor around by moving the guy around - more fun, and easier to handle than just a plain alligator clip.</td>
