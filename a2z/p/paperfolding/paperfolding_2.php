<td> If you look closely, you can kind of see how it is basically four simplified leaves put together (the tip of each leaf are the corners of the square). Forms like this - that can fold and unfold - are sometimes called deployable structures. An engineer named Davide De Focatiis has been studying leaves to design deployable structures. I found these patterns through his <a href="http://www.deployables.net/ddf/academic/deployable.html">web pages</a>. </td>
