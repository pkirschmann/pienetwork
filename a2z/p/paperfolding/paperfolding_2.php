<td> This is the coolest deployable structure I've found. It starts as a little cup-shaped thing you can hold in the palm of your hand and unfurls beautifully! This pattern was designed by Simon Guest. One really interesting thing about this structure is that the folds are slightly curved. You'll find two versions of the <a href="http://www2.eng.cam.ac.uk/%7Esdg/dstruct/wrapping.html">pattern on his web site</a>. One is simpler - it requires only moderate patience to make. The other requires extreme patience. But it turns out really nice. </td>
