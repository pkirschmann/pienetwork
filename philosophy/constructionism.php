      <div align="left"> <b><font face="Verdana, Arial, Helvetica, sans-serif">Constructionism<br>
        </font></b><font face="Verdana, Arial, Helvetica, sans-serif" size="-1">Work in the PIE Network is guided by the Constructionist approach to education pioneered by Seymour Papert of the MIT Media Lab. </font><font size="-1"><br>
                        </font>
                        <p></p>
      </div>
      <blockquote>
        <div align="left">
          <p><font face="Times New Roman, Times, serif">Constructionism is both a theory of learning and a strategy for education. It builds on the &quot;constructivist&quot; theories of Jean Piaget, asserting that knowledge is not simply transmitted from teacher to student, but actively constructed by the mind of the learner. Children don't <i>get</i> ideas; they <i>make</i> ideas. Moreover, constructionism suggests that learners are particularly likely to make new ideas when they are actively engaged in making some type of external artifact&#151;be it a robot, a poem, a sand castle, or a computer program&#151;which they can reflect upon and share with others. Thus, constructionism involves two intertwined types of construction: the construction of knowledge in the context of building personally meaningful artifacts. </font></p>
          <blockquote>
            <div align="left"></div>
          </blockquote>
