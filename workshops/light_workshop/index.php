            <p>We've done several variations on this workshop, but here's  how we described one of them  at the Science Museum:</p>
            <p><em>City Lights, Twinkling Lights </em>: Creating with Crickets</em><br>
              Play with Light! Explore light and color with interactive tools and cool materials. &nbsp; Make a tiny nightlight that glows, blinks, and changes color. Contribute your nightlight to a glowing landscape of twinkling lights. </p>
