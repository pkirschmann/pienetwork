          <td colspan="2"><p>Next, we looked at and talked about a variety of interesting 
              houses. I looked for examples of houses that did smart things (like 
              opening or closing skylights in response to temperature) or that 
              used unusual materials (like recycled shipping containers or packed 
              mud).</p>            <p>We found that <a href="http://www.dwellmag.com/magazine">Dwell 
              magazine</a> often features articles about futuristic houses that 
              are made of unusual materials or have high-tech or eco-friendly 
          features. </p></td>
