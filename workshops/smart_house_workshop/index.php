        <tr> 
          <td colspan="2"><p align="center">Photos and descriptions from Smart 
              House summer workshops at the Science Museum of Minnesota. </p>
            <p align="center">Create a high-tech dream home of the future. Using 
              crickets, PICO crickets or RCX and found materials, build and design 
              your mini-house. Add light, temperature, and touch sensors, and 
              program the house to do whatever you want&#8212;control the volume 
              of the stereo, open trap doors, scare away burglars, or dust itself!<br>
            </p></td>
        </tr>
