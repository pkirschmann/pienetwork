          <td width="172"><img src="../../a2z/s/smart_house_workshop/images/materials.jpg" width="150" height="200"></td>
          <td width="328"><ul>
              <li>Crickets, motors, and cables. </li>
              <li>Sensors - light sensors, touch sensors, and resistance sensors 
                are especially useful </li>
              <li>Copper foil </li>
              <li>Building supplies: cardboard, 1" pink insulation foam, tagboard, 
                wood scraps . </li>
              <li>Stuff to attach with: cable ties, pipe cleaners, hot glue, glue 
                sticks, masking and duct tape </li>
              <li>Interesting recycled stuff: tubes, cups, spoons, plastic stuff 
              </li>
              <li>Stuff to decorate with: fabric scaps, glittery paper, tinsel, 
                and mylar, construction paper, "doo-dads" (little plastic toys 
                & beads), yarn </li>
              <li>Foam </li>
              <li>A selection of LEGO pieces: gears, axles, axles connectors, 
                beams, [small grey pieces]. See the EZ modules pages for ideas 
                on LEGO supplies. </li>
