            <img src="../../a2z/images/line_500.gif" width="502" height="12"></div></td>
        </tr>
        <tr> 
          <td colspan="2"><ul>
              <li>become engaged in creating a house, and in the process,
                learn about robotics, computers,
                and engineering (even if you didn't think you were interested
                in or good at robotics, computers, and engineering)<br>
              </li>
              <li> get involved in a process of design and
                redesign, and working through problems when things don't work
                as expected<br>
              </li>
              <li>learn how you can combine familiar craft and building materials
                with digital materials</li>
            </ul></td>
        </tr>
