<td><h1 class="style3">Chain Reactions</h1></td>
</tr>
<tr>

<td valign="top"><table class="howToText" border="0" width="530" cellspacing="5" cellpadding="5" align="center">
        <tr align="left" valign="top"> 
          <td height="109" colspan="2"><div align="center"> 
              <p>A cat scratches a piece of string. The string pulls down a lever. 
                The lever releases a ball. The ball rolls down a track and turns 
                on a radio... </p>
              <p>In this class, we read a story (in which one thing leads to
                another, to another, to another) and then we built chain reactions.
                The chain reactions don't
                have to be just machines - they can tell a story, too. <br>
              </p>
            </div></td>
        </tr>
