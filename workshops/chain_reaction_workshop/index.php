              of the Workshop<br>
              <img src="../../a2z/images/line_500.gif" width="502" height="12"></div></td>
        </tr>
        <tr> 
          <td height="176" colspan="2"><p>- Get involved in a process 
              of design and redesign, and work through problems when things
              don't work as  expected</p>
            <p>- Collaborative design: Work with a group to make
              something, and coordinate with the other groups (before and after
              you) in the chain
              
              reaction</p>
            <p>- Think through different aspects of design: the materials, the
              design of the machine (&quot;Does it need to be heavier?
               sturdier?&quot;) and the program (&quot;Does it need to move slower? Does
              it 
              need to change directions?&quot;) <br>
              <br>
              </p>
          </td>
        </tr>
