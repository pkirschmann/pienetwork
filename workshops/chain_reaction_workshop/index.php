              <li>Copper foil</li>
              <li>Marbles - glass and metal</li>
              <li>Building supplies: cardboard, 1&quot; pink insulation foam, 
                tagboard, wood scraps </li>
              <li>Stuff to attach with: cable ties, pipe cleaners, hot glue, glue 
                sticks, masking and duct tape</li>
              <li>Stuff that can hold or move a marble: tubes, cups, spoons</li>
              <li>Stuff to decorate with: glittery paper, tinsel, and mylar, construction 
                paper, &quot;doo-dads&quot; (little plastic toys &amp; beads), 
                yarn </li>
