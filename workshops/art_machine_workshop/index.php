<td><h1 class="style3">Art Making Machines</h1></td>
</tr>
<tr>

<td><table class="howToText" border="0" width="535" cellspacing="5" cellpadding="5" align="center">
        <tr> 
          <td colspan="2"><div align="center">Mix paint-brushes pigment, canvas 
              and craft materials. In this workshop you'll use programmable bricks, 
              buckets of paint, paper, canvas, and motors to make an animated 
              art machine. Use sensors to explore color and light. Program your 
              machine to react to an audience to spin faster and slower, to create 
              complex abstract designs, or to simply fling pigment! </div></td>
        </tr>
        <tr> 
          <td colspan="2"><div align="center" class="style2">Goals of the Workshop<img src="/a2z/images/line_500.gif" width="502" height="12"></div></td>
        </tr>
        <tr> 
          <td colspan="2"><p>- engaging students who might not be interested in 
              robots, computers, or engineering</p>
            <p>- getting students involved in a process of design and redesign, 
              and working through problems when things don't work as they expect. 
            </p>
            <p>- thinking through the design of something in multiple ways: the 
              materials (the pen or paint, for example), the design of the machine 
              (does it need to be heavier? sturdier?) and the program (does it 
              need to move slower? does it need to change directions? )</p></td>
        </tr>
        <!-- THE DIRECTIONS OR TEXT AND THE IMAGES GO ALONG HERE -->
        <tr> 
          <td colspan="2"><div align="center" class="style2">Materials<img src="/a2z/images/line_500.gif" width="502" height="12"></div></td>
        </tr>
        <tr> 
          <td width="173"><img src="/a2z/a/art_machine_workshop/images/materials.jpg" width="148" height="350"></td>
          <td width="327"><ul>
              <li>Computers</li>
              <li>Crickets or RCX bricks </li>
              <li>Lots of batteries </li>
              <li>A large cloth or paper dropcloth plus some large sheets of kraft 
                paper for testing machines </li>
              <li>Tempera paints </li>
              <li>Tape </li>
              <li>Textured materials that hold paint (sponges, textured rollers 
                for house painting, fun fur, that foamy craft stuff) </li>
              <li>A variety of 1/2"to 3" brushes (small, cheap craft brushes, 
                metal rubber cement brushes, foam brushes)</li>
              <li>Other materials: cardboard tubes, cardboard, string dowels (get 
                the size that fits into Lego holes) styrofoam balls plastic or 
                paper cups, plastic or paper plates (use these to dispense paint 
                as well as for making art machines) an assortment of colored construction 
                paper </li>
              <li>Low-temperature hot melt glue </li>
            </ul></td>
        </tr>
        <tr> 
          <td colspan="2"><div align="center" class="style2">Set Up<br>
          <img src="/a2z/images/line_500.gif" width="502" height="12"></div></td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/Image3.jpg" width="150" height="128"></td>
          <td>We have held this workshop for groups of 9-12 year-old kids, and 
            for younger kids (who came with a parent or other adult). With younger 
            kids (ages 5-8) we needed more adult helpers.</td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/painttable_150.jpg" width="150" height="196"></td>
          <td>We set up two tables of materials. One table-- the &quot;dry&quot; 
            table --held all the building and construction materials. The other--the 
            &quot;wet&quot; table-- held all the paint and water. This table was 
            close to the tarp and had paper and brushes and space for kids to 
            load their machines with paint. </td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/tarp.jpg" width="150" height="113"></td>
          <td>We taped down a large tarp (or paper painter's dropcloth) for painting. 
            The tarp was large enough that many kids could try their machines 
            at once. All the machines together created a huge painting. </td>
        </tr>
        <tr> 
          <td colspan="2"><div align="center" class="style2">Introduction<img src="/a2z/images/line_500.gif" width="502" height="12"></div></td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/talking.jpg" width="150" height="94"></td>
          <td>We begin workshop by gathering as a group and talking a little about 
            the cricket. We demonstrate a couple of the painters, and talk as 
            a group about what works and what doesn't work as well. </td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/program.gif" width="150" height="182"></td>
          <td>Next, we write a simple program the kids a simple program and try 
            it out with a machine. We start with just a couple of beeps, then 
            add the motion. It is handy to have a projector so everyone can see 
            the progam as you work.</td>
        </tr>
        <tr> 
          <td colspan="2"><div align="center" class="style2">Working &amp; Playing<img src="/a2z/images/line_500.gif" width="502" height="12"></div></td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/Image8.jpg" width="150" height="143"></td>
          <td>After a quick introduction to progamming, it was time to build. 
            We left samples out and partially built machines around. </td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/circlepens.jpg" width="150" height="152"></td>
          <td> <p>In one of our workshops, we emphasized the art materials over 
              the Lego pieces. In that workshop, kids built machines that were 
              primarily art materials, using only the motors from the kits. They 
              built pretty quickly and were then ready to program. </p></td>
        </tr>
        <tr>
          <td><img src="/a2z/a/art_machine_workshop/images/testing.jpg" width="150"></td>
          <td>The kids generally tried out the program once without paint, just 
            to trouble-shoot, and then went directly to load up with paint and 
            try it out on the tarp. </td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/Image6.jpg" width="150" height="160"></td>
          <td>We didn't worry too much about getting paint on stuff. Tempera paint 
            is water-soluble and will wash off the floor or Lego pieces. Offer 
            paint shirts to kids who might worry about getting their clothes dirty. 
          </td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/fixing.jpg" width="150" height="127"></td>
          <td><p>Testing often led to rebuilding. The paint doesn't go on the 
              way you expect, or the machine doesn't move the same way once you 
              attach pens. </p>
            <p>&nbsp;</p></td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/taping.jpg" width="150" height="113"></td>
          <td>In this photo the kids are reinforcing their design with tape. Kids 
            moved back and forth between their computers, the supplies, and the 
            paint table.</td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/Image4.jpg" width="150" height="231"></td>
          <td>Kids had to vary how long the machine ran (they often thought 3 
            seconds would be a really, really long time), or make it change directions, 
            or figure out how to build the machine a little differently to work 
            better. </td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/spin-hands.jpg" width="150" height="106"></td>
          <td><p>Most of the machines kids made were designed to moved the paint 
              around the paper. It's also possible to make the paper move. That's 
              the way this spin art machine works. </p>
            <p><a href="/a2z/s/spinart/index.php">Read how to make a spin art 
              machine.</a></p></td>
