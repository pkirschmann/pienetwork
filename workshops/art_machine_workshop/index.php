            Other Thoughts &amp; 
              Reflections<img src="/a2z/images/line_500.gif" width="502" height="12"></div></td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/Image5.jpg" width="150" height="206"></td>
          <td>With young kids, we needed a lots of helpers, both for getting set 
            up and for helping the kids once they were working. Parents helped 
            the kids build, but we needed to talk them through programming, and 
            they all got to that stage at about the same time. </td>
        </tr>
        <tr> 
          <td>&nbsp;</td>
          <td>Generally, the parents were really good about helping and let us 
            work directly with the kids</td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/everything.jpg" width="150" height="126"></td>
          <td>Kids used both the art materials and the Lego bricks and other materials 
            (wheels, etc.) Generally, it was easier to use the art materials for 
            both the painter part and the machine, and use as few Lego pieces 
            as possible. Cardboard and hot melt glue let you assemble something 
            really quickly. The cups and plates were also good for basic machine 
            structures.</td>
        </tr>
        <tr> 
          <td><img src="/a2z/a/art_machine_workshop/images/Image7.jpg" width="149" height="242"></td>
