&nbsp;&nbsp;<b>pinhole cricket-cam</b>
<br>&nbsp;&nbsp;Added: Wednesday, November 12th, 2003
<br>&nbsp;&nbsp;What kind of idea: half-baked
<br>&nbsp;&nbsp;<a href="http://www.pinholespy.com">Related webpage</a>
</td>

<td align="left" valign="top">
Inspired by Margaret's work on using crikets to make photographs, I got to thinkin'....  A criket could be used to advance a roll of film.  Pinhole cameras don't require a lense to focus light so they're often home-made.  Could a cricket be used to advance a roll of film so that you could make a pinhole camera that would make multiple exposures??  Furthermore could a light sensor judge when the film was exposed?  After processing, under-exposed negatives are transparent while over-exposed negatives are nearly opaque.  Does any darkening occur at the time of exposure, before the negatives are fixed in chemical baths??  If so, you could place the light sensor under the film and use it to trigger a shutter to close after the film has become opaque and begins to block the light from reaching the sensor.

Posted by Chris 
</td>

